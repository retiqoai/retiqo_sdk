class PayloadRequest(Request):
    """Payload request (for RTI method calls)"""

    def __init__(self, channel_id: str, payload: bytes):
        """Initialize payload request"""
        super().__init__()
        self.type = "payload"
        # Payload data is a hex string, not base64
        # The server expects hex encoding for the payload
        import binascii
        payload_hex = binascii.hexlify(payload).decode("utf-8")
        self.data = {
            "channelid": channel_id,  # Field names are lowercase on the wire
            "payload": payload_hex,  # Hex-encoded payload
        }

    def get_verification_data(self) -> bytes:
        """Get verification data - returns (payload.dataIn + channelId) as bytes"""
        # Verification data: payload hex followed by the channel ID
        # payload.dataIn is the hex string of the payload
        payload_hex = self.data.get("payload", "")
        channel_id = self.data.get("channelid") or self.data.get("channelId") or ""
        # Concatenate hex string payload and channel ID, then convert to bytes
        if not channel_id:
            raise ValueError(f"channel_id is None or empty in PayloadRequest. Data keys: {list(self.data.keys())}")
        verification_str = payload_hex + channel_id
        return verification_str.encode("utf-8")

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary"""
        result = super().to_dict()
        result["type"] = self.type
        result["data"] = self.data
        return result


class PayloadResult(Result):
    """Payload result"""

    def __init__(self, status: int = 0, description: str = "", payload: Optional[bytes] = None):
        """Initialize payload result"""
        super().__init__(status, description)
        self.payload = payload

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PayloadResult":
        """Create from dictionary"""
        payload_data = data.get("data", {}).get("payload")
        payload = None
        if payload_data:
            # Server sends Payload as an object with dataIn field (hex string)
            # or as a hex string directly
            if isinstance(payload_data, dict):
                # It's a Payload object: {"dataIn": "hex_string"}
                hex_str = payload_data.get("datain") or payload_data.get("dataIn")
                if hex_str:
                    import binascii
                    payload = binascii.unhexlify(hex_str)
            elif isinstance(payload_data, str):
                # It's a hex string directly
                import binascii
                try:
                    payload = binascii.unhexlify(payload_data)
                except (binascii.Error, ValueError):
                    # Try base64 as fallback
                    try:
                        payload = base64.b64decode(payload_data)
                    except Exception:
                        payload = None
        return cls(
            status=data.get("status", 0),
            description=data.get("description", ""),
            payload=payload,
        )


